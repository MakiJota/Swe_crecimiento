# -*- coding: utf-8 -*-
# Paso 08 · Sitio publico con los resultados de Angel para Suecia, en docs/ (GitHub Pages,
# tema Just the Docs), en ingles en la raiz y en sueco en docs/sv/.
# Adaptado de Rpipe/scripts/08_sitio.R (Argentina). Los calculos, graficos, mapas y textos
# son los de lib/resultados.R, los mismos que usa el reporte (06_reporte.R); aca solo se
# arman las paginas.
#
# Salida (todo generado, se pisa en cada corrida):
#   docs/_config.yml, docs/index.md, docs/method.md, docs/sweden.md,
#   docs/cities/index.md, docs/cities/<slug>.md,
#   docs/sv/index.md, docs/sv/metod.md, docs/sv/sverige.md, docs/sv/stader/index.md,
#   docs/sv/stader/<slug>.md,
#   docs/assets/img/<lang>/ (graficos y leyenda), docs/assets/img/maps/ (mapas, sin texto)
#
# Uso: Rscript Sweden/scripts/08_sitio.R [--sin-mapas]

script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
SCRIPTS <- normalizePath(dirname(script), winslash = "/")
RPIPE <- dirname(SCRIPTS)
source(file.path(SCRIPTS, "lib", "cajas.R"))
SIN_MAPAS <- "--sin-mapas" %in% commandArgs(trailingOnly = TRUE)

# repo de GitHub del sitio: decide la URL (https://makijota.github.io/<REPO_NOMBRE>/)
REPO_NOMBRE <- "Swe_crecimiento"
REPO <- sprintf("https://github.com/MakiJota/%s", REPO_NOMBRE)
DOCS <- file.path(RPIPE, "docs")
for (d in c("cities", "sv/stader")) dir.create(file.path(DOCS, d), recursive = TRUE, showWarnings = FALSE)

url <- function(p) sprintf("{{ '%s' | relative_url }}", p)
escribir <- function(lineas, ...) writeLines(enc2utf8(lineas), do.call(file.path, as.list(c(DOCS, ...))),
                                             useBytes = TRUE)
encabezado <- function(titulo, orden, extra = character(), permalink = NULL)
  c("---", sprintf('title: "%s"', titulo), sprintf("nav_order: %d", orden),
    if (!is.null(permalink)) sprintf("permalink: %s", permalink), extra, "---", "")
toc <- c("1. TOC", "{:toc}", "")
# la misma pagina en el otro idioma
cambio <- function(en, sv) c(sprintf("[%s](%s)", tr("På svenska", "In English"), url(tr(sv, en))), "")

# rutas de cada idioma: la misma pagina, en ingles y en sueco
RUTA <- list(en = list(inicio = "/", metodo = "/method/", pais = "/sweden/", ciudades = "/cities/",
                       ciudad = "/cities/%s/"),
             sv = list(inicio = "/sv/", metodo = "/sv/metod/", pais = "/sv/sverige/", ciudades = "/sv/stader/",
                       ciudad = "/sv/stader/%s/"))

# _config.yml: uno solo, en ingles
escribir(c(
  "title: Urban growth in Sweden's cities",
  "description: Angel / Atlas of Urban Expansion classes on GISD30, Swedish cities, 1990-2020",
  "remote_theme: just-the-docs/just-the-docs@v0.10.1",
  "plugins:", "  - jekyll-remote-theme",
  sprintf('baseurl: "/%s"', REPO_NOMBRE),
  "permalink: pretty",
  "search_enabled: true",
  "aux_links:", sprintf('  "Code on GitHub": "%s"', REPO),
  sprintf('footer_content: "Exploratory results. Generated by <code>scripts/08_sitio.R</code> from GISD30 (Zhang et al. 2022, CC BY 4.0) and SCB tätorter 2020 on %s."',
          format(Sys.Date()))), "_config.yml")

for (LANG in c("en", "sv")) {
  source(file.path(SCRIPTS, "lib", "resultados.R"))
  R <- RUTA[[LANG]]
  O <- RUTA[[setdiff(c("en", "sv"), LANG)]]
  IMG <- file.path(DOCS, "assets", "img", LANG)
  r <- cargar_resultados(RPIPE)
  graficos(r, IMG)
  if (!SIN_MAPAS && LANG == "en") mapas(r, file.path(DOCS, "assets", "img", "maps"))

  img <- function(ruta, alt) sprintf("![%s](%s)", alt, url(sprintf("/assets/img/%s/%s", LANG, ruta)))
  enlace <- function(s) sprintf("[%s](%s)", r$fichas$nombre[r$fichas$slug == s], url(sprintf(R$ciudad, s)))
  mapas_html <- function(s) c(
    '<div style="display:grid;grid-template-columns:repeat(auto-fit,minmax(300px,1fr));gap:10px">',
    vapply(ANIOS, function(a) {
      u <- url(sprintf("/assets/img/maps/%s_%d.png", s, a))
      sprintf('<a href="%s"><img src="%s" alt="%s %d" loading="lazy" style="width:100%%"></a>', u, u,
              r$fichas$nombre[r$fichas$slug == s], a)
    }, ""),
    "</div>", "", tr("Click a map for full size.", "Klicka på en karta för full storlek."))
  ca <- function(clave, s = NULL) {
    # enlace a la misma pagina en el otro idioma
    en <- if (LANG == "en") R else O
    sv <- if (LANG == "sv") R else O
    if (is.null(s)) cambio(en[[clave]], sv[[clave]]) else cambio(sprintf(en[[clave]], s), sprintf(sv[[clave]], s))
  }
  # en sueco todo cuelga de la pagina "Svenska"
  t_ini <- tr("Home", "Svenska")
  t_met <- tr("Method", "Metod")
  t_pais <- tr("Sweden", "Sverige")
  t_ciu <- tr("Cities", "Städer")
  hijo <- if (LANG == "sv") "parent: Svenska" else character()
  base <- if (LANG == "sv") 10 else 0
  dir_pais <- if (LANG == "sv") c("sv", "sverige.md") else "sweden.md"
  dir_met <- if (LANG == "sv") c("sv", "metod.md") else "method.md"
  dir_ciu <- if (LANG == "sv") c("sv", "stader") else "cities"

  escribir(c(encabezado(t_ini, base + 1, if (LANG == "sv") "has_children: true", R$inicio),
    ca("inicio"),
    tr("# Urban growth in Sweden's cities, 1990-2020", "# Stadstillväxt i Sveriges städer, 1990-2020"), "",
    sprintf(tr("How the %d largest Swedish cities (SCB tätorter, 2020) grew between 1990 and 2020, measured with the classes of the **Atlas of Urban Expansion** (Angel et al. 2016) on the **GISD30** impervious-surface record (Landsat, 30 m).",
               "Hur Sveriges %d största städer (SCB:s tätorter, 2020) växte mellan 1990 och 2020, mätt med klasserna i **Atlas of Urban Expansion** (Angel m.fl. 2016) på **GISD30**, en serie över hårdgjord yta (Landsat, 30 m)."), r$n), "",
    tr("The question behind every page: **how much does it change the picture to count the fringe open space** (the 100 m ring of unbuilt land around urban and suburban built-up) as part of the city?",
       "Frågan bakom varje sida: **hur mycket ändras bilden om man räknar den öppna randzonen** (ringen på 100 m obebyggd mark runt urban och förortsbebyggelse) som en del av staden?"), "",
    paste("##", tr("In one paragraph", "I ett stycke")), "", resumen_md(r), "",
    paste("##", tr("Pages", "Sidor")), "",
    sprintf(tr("- [Method](%s): data, classes, how \"the city\" is chosen, metrics, caveats.",
               "- [Metod](%s): data, klasser, hur \"staden\" väljs, mått, förbehåll."), url(R$metodo)),
    sprintf(tr("- [Sweden](%s): totals and the comparison of all %d cities.",
               "- [Sverige](%s): summor och jämförelse av alla %d städer."), url(R$pais), r$n),
    sprintf(tr("- [Cities](%s): one page each, with its growth charts and four maps.",
               "- [Städer](%s): en sida per stad, med tillväxtdiagram och fyra kartor."), url(R$ciudades)), "",
    paste("##", tr("Status", "Status")), "",
    tr("Exploratory. Every number on this site is recomputed from the pipeline outputs; none is typed by hand. The method is the one used for Argentina's agglomerations, with SCB tätorter in place of the Argentine perimeters.",
       "Explorativt. Varje siffra på webbplatsen räknas om från kedjans utdata; ingen skrivs in för hand. Metoden är densamma som för Argentinas tätorter, med SCB:s tätorter i stället för de argentinska gränserna."), "",
    sprintf(tr("Code: [%s](%s).", "Kod: [%s](%s)."), REPO, REPO)),
    if (LANG == "sv") c("sv", "index.md") else "index.md")

  escribir(c(encabezado(t_met, base + 2, hijo, R$metodo), ca("metodo"), paste("#", t_met), "", toc,
    metodo_md(r), "",
    paste("##", tr("Pipeline", "Kedjan")), "",
    tabla(tr(c("Step", "Script", "What it does"), c("Steg", "Skript", "Vad det gör")), list(
      c("00", "`00_gisd30_descarga.R`", tr("GISD30 tiles for Sweden (Zenodo, md5 checked)", "GISD30-rutor för Sverige (Zenodo, md5 kontrollerad)")),
      c("01", "`01_gisd30_decadas.R`", tr("eight five-year epochs to four cumulative decades", "åtta femårsperioder till fyra kumulativa decennier")),
      c("07", "`07_limites_aglomerados.R`", tr("SCB tätorter 2020 for the chosen cities, and their boxes", "SCB:s tätorter 2020 för de valda städerna, och deras rutor")),
      c("04b", "`04b_angel_sin_landsat.R`", tr("Angel classes and metrics per decade", "Angels klasser och mått per decennium")),
      c("06", "`06_reporte.R`", tr("the same results as one markdown report per language", "samma resultat som en markdown-rapport per språk")),
      c("08", "`08_sitio.R`", tr("this site", "den här webbplatsen")))), "",
    paste("##", tr("References", "Referenser")), "",
    "- Angel, S. et al. (2016). *Atlas of Urban Expansion, 2016 Edition. Volume 1: Areas and Densities.* NYU, UN-Habitat, Lincoln Institute of Land Policy.",
    "- Angel, S., Parent, J. & Civco, D. (2007). Urban sprawl metrics: an analysis of global urban expansion using GIS. ASPRS Annual Conference.",
    "- Statistiska centralbyrån (SCB). Statistiska tätorter 2020, öppna geodata.",
    "- Zhang, X. et al. (2022). GISD30: global 30 m impervious-surface dynamic dataset from 1985 to 2020 using time-series Landsat imagery on the Google Earth Engine platform. *Earth System Science Data* 14, 1831-1856."),
    dir_met)

  escribir(c(encabezado(t_pais, base + 3, hijo, R$pais), ca("pais"),
             paste("#", tr("Sweden: all cities together", "Sverige: alla städer tillsammans")), "", toc,
             sverige_md(r, img, enlace)), dir_pais)

  escribir(c(encabezado(t_ciu, base + 4, c("has_children: true", hijo), R$ciudades), ca("ciudades"),
    paste("#", t_ciu), "",
    sprintf(tr("One page for each of the %d cities: how it grew by Angel class, the effect of counting the fringe, and maps for 1990, 2000, 2010 and 2020.",
               "En sida för var och en av de %d städerna: hur den växte per Angel-klass, effekten av randzonen och kartor för 1990, 2000, 2010 och 2020."), r$n), "",
    tabla(tr(c("City", "County", "population 2020", "extent 2020 (km²)", "built-up growth (% / yr)", "pace", "shape"),
             c("Stad", "Län", "befolkning 2020", "utbredning 2020 (km²)", "tillväxt bebyggd mark (% / år)", "takt", "form")),
          lapply(seq_len(nrow(r$fichas)), function(i) with(r$fichas[i, ], c(enlace(slug), provincia, f0(bef),
            f1(extension_2020), f2(t_construido), as.character(ritmo), forma))))),
    dir_ciu, "index.md")

  padre <- if (LANG == "sv") c("parent: Städer", "grand_parent: Svenska") else "parent: Cities"
  # menu en orden alfabetico sueco (a, a, o con tilde despues de la z), las tablas por poblacion
  clave <- chartr("åäö", "{|}", tolower(r$fichas$nombre))
  orden_menu <- match(seq_along(clave), order(clave, method = "radix"))   # radix: orden C, no del locale
  for (i in seq_len(nrow(r$fichas))) {
    s <- r$fichas$slug[i]
    escribir(c(encabezado(r$fichas$nombre[i], orden_menu[i], padre, sprintf(R$ciudad, s)), ca("ciudad", s),
               sprintf("# %s", r$fichas$nombre[i]), "", ciudad_md(r, s, img, mapas_html)),
             dir_ciu, sprintf("%s.md", s))
  }
  # paginas de ciudades que ya no estan (por si cambia la lista)
  carpeta <- do.call(file.path, as.list(c(DOCS, dir_ciu)))
  viejas <- setdiff(sub("\\.md$", "", list.files(carpeta, "\\.md$")), c("index", r$fichas$slug))
  unlink(file.path(carpeta, paste0(viejas, ".md")))
  cat(sprintf("Sitio (%s) escrito en %s: %d ciudades\n", LANG, DOCS, r$n))
}
