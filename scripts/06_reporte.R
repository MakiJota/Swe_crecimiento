# -*- coding: utf-8 -*-
# Paso 06 · Reporte de las metricas de Angel para las ciudades suecas, en ingles y en sueco.
# Adaptado de Rpipe/scripts/06_reporte.R (Argentina). Se genera entero desde resumen.csv con
# lib/resultados.R, asi que ningun numero se escribe a mano.
#
# Salida, pensada para leerse en GitHub o en la vista previa de VS Code:
#   reporte/REPORT_en.md, reporte/REPORT_sv.md
#   reporte/img/<lang>/sverige_*.png, reporte/img/<lang>/agl/<slug>_*.png, reporte/img/<lang>/leyenda.png
#   reporte/img/maps/<slug>_<anio>.png   (los mapas no llevan texto: uno solo para los dos idiomas)
# Las imagenes van con rutas relativas al .md: se mueve la carpeta reporte/ entera.
#
# Uso: Rscript Sweden/scripts/06_reporte.R [--sin-mapas] [--lang en|sv]

script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
SCRIPTS <- normalizePath(dirname(script), winslash = "/")
RPIPE <- dirname(SCRIPTS)
source(file.path(SCRIPTS, "lib", "cajas.R"))
args <- commandArgs(trailingOnly = TRUE)
SIN_MAPAS <- "--sin-mapas" %in% args
IDIOMAS <- if ("--lang" %in% args) args[match("--lang", args) + 1] else c("en", "sv")

SAL <- file.path(RPIPE, "reporte")
dir.create(SAL, recursive = TRUE, showWarnings = FALSE)
OTRO <- c(en = "[På svenska](REPORT_sv.md)", sv = "[In English](REPORT_en.md)")

# ancla de un encabezado como la arma GitHub: minusculas, sin puntuacion, espacios a guion
ancla <- function(x) gsub(" ", "-", gsub("[^\\p{L}\\p{N} _-]", "", tolower(x), perl = TRUE))

for (LANG in IDIOMAS) {
  # resultados.R fija las etiquetas segun LANG al cargarse: se vuelve a cargar por idioma
  source(file.path(SCRIPTS, "lib", "resultados.R"))
  IMG <- file.path(SAL, "img", LANG)
  r <- cargar_resultados(RPIPE)
  graficos(r, IMG)
  if (!SIN_MAPAS && LANG == IDIOMAS[1]) mapas(r, file.path(SAL, "img", "maps"))

  img <- function(ruta, alt) sprintf("![%s](img/%s/%s)", alt, LANG, ruta)
  enlace <- function(s) {
    nm <- r$fichas$nombre[r$fichas$slug == s]
    sprintf("[%s](#%s)", nm, ancla(nm))
  }
  mapas_html <- function(s) {
    celda <- function(a) sprintf('<td><a href="img/maps/%s_%d.png"><img src="img/maps/%s_%d.png" width="420" alt="%d"></a></td>',
                                 s, a, s, a, a)
    c("<table>", paste0("<tr>", celda(1990), celda(2000), "</tr>"),
      paste0("<tr>", celda(2010), celda(2020), "</tr>"), "</table>")
  }
  h_res <- tr("Summary", "Sammanfattning")
  h_met <- tr("Method", "Metod")
  h_swe <- tr("Sweden", "Sverige")
  h_ciu <- tr("Cities", "Städer")
  h_ind <- tr("Contents", "Innehåll")

  L <- c(
    sprintf(tr("# Angel / Atlas 2016 metrics on GISD30 · %d Swedish cities, 1990-2020",
               "# Angel / Atlas 2016-mått på GISD30 · %d svenska städer, 1990-2020"), r$n), "",
    OTRO[[LANG]], "",
    sprintf(tr("Exploratory. The whole report, every number and every label included, is generated by `scripts/06_reporte.R` from `outputs/angel/resumen.csv` (step 04b). Run of %s.",
               "Explorativt. Hela rapporten, varje siffra och varje etikett, genereras av `scripts/06_reporte.R` från `outputs/angel/resumen.csv` (steg 04b). Körning %s."),
            format(Sys.Date())), "",
    tr("**Question:** how is each city growing, and how much does it change the picture to count the *fringe open space* (the 100 m ring of unbuilt land around urban and suburban built-up) as part of the city?",
       "**Fråga:** hur växer varje stad, och hur mycket ändras bilden om man räknar den *öppna randzonen* (ringen på 100 m obebyggd mark runt urban och förortsbebyggelse) som en del av staden?"), "",
    paste("##", h_ind), "",
    sprintf("1. [%s](#%s)", h_res, ancla(h_res)), sprintf("2. [%s](#%s)", h_met, ancla(h_met)),
    sprintf("3. [%s](#%s)", h_swe, ancla(h_swe)),
    sprintf("4. [%s](#%s): %s", h_ciu, ancla(h_ciu), paste(vapply(r$fichas$slug, enlace, ""), collapse = " · ")), "",
    paste("##", h_res), "", resumen_md(r), "",
    paste("##", h_met), "", metodo_md(r, h = "###"), "",
    tr("### Pipeline (`scripts/`)", "### Kedjan (`scripts/`)"), "",
    tabla(tr(c("Step", "Script", "What it does"), c("Steg", "Skript", "Vad det gör")), list(
      c("00", "`00_gisd30_descarga.R`", tr("GISD30 tiles for Sweden (Zenodo, md5 checked)", "GISD30-rutor för Sverige (Zenodo, md5 kontrollerad)")),
      c("01", "`01_gisd30_decadas.R`", tr("eight five-year epochs to four cumulative decades", "åtta femårsperioder till fyra kumulativa decennier")),
      c("07", "`07_limites_aglomerados.R`", tr("SCB tätorter 2020 for the chosen cities, and their boxes in `cajas.md`", "SCB:s tätorter 2020 för de valda städerna, och deras rutor i `cajas.md`")),
      c("04b", "`04b_angel_sin_landsat.R`", tr("Angel classes and metrics per decade, GISD30 cut with each box", "Angels klasser och mått per decennium, GISD30 klippt med varje ruta")),
      c("06", "`06_reporte.R`", tr("this report, in English and Swedish", "den här rapporten, på engelska och svenska")),
      c("08", "`08_sitio.R`", tr("the same results as a GitHub Pages site", "samma resultat som en GitHub Pages-webbplats")))), "",
    paste("##", h_swe), "", sverige_md(r, img, enlace, h = "###"), "",
    paste("##", h_ciu), "")
  for (s in r$fichas$slug) {
    L <- c(L, sprintf("### %s", r$fichas$nombre[r$fichas$slug == s]), "",
           ciudad_md(r, s, img, mapas_html, h = "####"), "",
           sprintf("[%s](#%s)", tr("Back to contents", "Tillbaka till innehållet"), ancla(h_ind)), "")
  }
  archivo <- file.path(SAL, sprintf("REPORT_%s.md", LANG))
  writeLines(enc2utf8(L), archivo, useBytes = TRUE)
  cat(sprintf("Reporte escrito en %s: %d ciudades\n", archivo, r$n))
}
